export function parseKoreanAddress(address: string): { sido: string | null; sigungu: string | null } {
  const tokens = address.trim().split(/\s+/)
  if (tokens.length === 0) return { sido: null, sigungu: null }

  const sido = SIDO_ALIASES[tokens[0]] ?? null
  if (!sido || !tokens[1]) return { sido, sigungu: null }

  // "수원시 팔달구"처럼 시+구가 함께 오면 합쳐서, 그 외엔 두 번째 토큰만 시/군/구로 사용
  let sigungu = tokens[1]
  if (tokens[2] && /시$/.test(tokens[1]) && /구$/.test(tokens[2])) {
    sigungu = `${tokens[1]} ${tokens[2]}`
  }

  return { sido, sigungu }
}
